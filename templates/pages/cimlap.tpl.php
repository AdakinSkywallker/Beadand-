<h2>Bemutató bloggá vált.</h2>

<p>
    Aztán átalakult valami mássá. Ablakká, amelyben kitekinthetek a világra,
    a világ meg betekinthet a gondolataimba: késekről, every day carry
    felszerelésekről, és az ezek mögött meghúzódó filozófiáról.
</p>

<p>
    Aztán ennél is több lett. Egy közösség, amelyben együtt, hasonló értékek
    mentén dolgozunk azért, hogy egy minőségi, kissé talán régimódi
    találkahely legyen ez az online térben.
</p>

<p>
    Balogh József vagyok, és azon dolgozom, hogy ez a közösség egyre nagyobbá
    váljon, és együtt adhassuk tovább ezek az értékeket. Tarts velünk te is!
</p>


<h2>De mi az az EDC?</h2>

<p>
    Egy angol betűszó, amely kibontva az every day carry kifejezést takarja.
    Ez szó szerinti fordításban azokat a holmikat jelenti, amelyeket nap mint
    nap magunknál hordunk. A közkeletű tévhittel ellentétben nem szükséges az,
    hogy mindig minden nap nálunk legyen: inkább egyfajta készletről,
    gyűjteményről van szó, amelynek elemeit az adott szituációnak megfelelően
    váltogathatjuk. Más holmikat pakolunk el, ha egy irodába megyünk dolgozni,
    mást, ha egy építkezésen melózunk, és akkor is, amikor hétvégén
    rokonlátogatóba megyünk.
</p>

<p>
    Ezen a blogon főképp késekről olvashatsz, mert hozzám ezek az eszközök
    állnak legközelebb, de szó esik néha másról is. Multiszerszámokról,
    táskákról, egyéb kiegészítőkről. És nem csak bemutatókat készítek:
    ahogy már írtam, sokféle aspektusa érdekel ennek a világnak.
</p>

<p>
    Az every day carry tehát sok minden lehet. Életmód, filozófia, hobbi,
    vagy akár egy gyűjtőszenvedély alapja. Mindegy, hogy téged melyik része
    érdekel, remélem, találsz itt értékes olvasnivalót.
</p>


